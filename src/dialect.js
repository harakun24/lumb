/**
 * Menyediakan aturan sintaks SQL spesifik untuk SQLite, PostgreSQL, dan MySQL/MariaDB
 */
export function createDialect(name = "sqlite") {
  const normalized = normalizeDialectName(name);

  function quoteId(identifier) {
    if (!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(identifier)) {
      throw new Error(`Nama identifier SQL tidak valid: "${identifier}".`);
    }
    return normalized === "mysql" ? `\`${identifier}\`` : `"${identifier}"`;
  }

  function param(index) {
    return normalized === "postgres" ? `$${index}` : "?";
  }

  function serialize(val) {
    if (val === undefined || val === null) return null;
    if (typeof val === "boolean") {
      return normalized === "postgres" ? val : (val ? 1 : 0);
    }
    if (val instanceof Date) {
      if (normalized === "mysql") {
        return val.toISOString().slice(0, 23).replace("T", " ");
      }
      return val.toISOString();
    }
    return val;
  }

  function escapeLiteral(val) {
    const serialized = serialize(val);
    if (serialized === null) return "NULL";
    if (typeof serialized === "boolean") return serialized ? "TRUE" : "FALSE";
    if (typeof serialized === "number") return String(serialized);
    return `'${String(serialized).replace(/'/g, "''")}'`;
  }

  function mapColumnType(col) {
    if (col.isPrimaryKey && col.isAutoIncrement) {
      if (normalized === "postgres") return "INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
      if (normalized === "mysql") return "INT AUTO_INCREMENT PRIMARY KEY";
      return "INTEGER PRIMARY KEY AUTOINCREMENT";
    }

    switch (col.jsType) {
      case "Number":
        if (col.isInteger) {
          return normalized === "sqlite" ? "INTEGER" : "INT";
        }
        if (normalized === "postgres") return "DOUBLE PRECISION";
        if (normalized === "mysql") return "DOUBLE";
        return "REAL";

      case "Boolean":
        if (normalized === "postgres") return "BOOLEAN";
        if (normalized === "mysql") return "TINYINT(1)";
        return "INTEGER";

      case "Date":
        if (normalized === "postgres") return "TIMESTAMPTZ";
        if (normalized === "mysql") return "DATETIME(3)";
        return "TEXT";

      case "String":
      default:
        if (col.length !== null && col.length !== undefined) {
          return normalized === "sqlite" ? "TEXT" : `CHAR(${Number(col.length)})`;
        }
        if (col.max !== null && col.max !== undefined) {
          return normalized === "sqlite" ? "TEXT" : `VARCHAR(${Number(col.max)})`;
        }
        if (normalized === "mysql") return "VARCHAR(255)";
        return "TEXT";
    }
  }

  function lengthFn(quotedCol) {
    return normalized === "mysql" ? `CHAR_LENGTH(${quotedCol})` : `LENGTH(${quotedCol})`;
  }

  function insertSql(tableQuoted, colsQuoted, placeholders, pkQuoted, hasAutoPk) {
    if (!colsQuoted) {
      if (normalized === "mysql") {
        return `INSERT INTO ${tableQuoted} () VALUES ();`;
      }
      if (normalized === "postgres" && hasAutoPk) {
        return `INSERT INTO ${tableQuoted} DEFAULT VALUES RETURNING ${pkQuoted};`;
      }
      return `INSERT INTO ${tableQuoted} DEFAULT VALUES;`;
    }
    if (normalized === "postgres" && hasAutoPk) {
      return `INSERT INTO ${tableQuoted} (${colsQuoted}) VALUES (${placeholders}) RETURNING ${pkQuoted};`;
    }
    return `INSERT INTO ${tableQuoted} (${colsQuoted}) VALUES (${placeholders});`;
  }

  function upsertSql(tableQuoted, colsQuoted, allPlaceholders, pkQuoted, updateCols, mode) {
    if (normalized === "mysql") {
      if (mode === "ignore" || updateCols.length === 0) {
        return `INSERT IGNORE INTO ${tableQuoted} (${colsQuoted}) VALUES ${allPlaceholders};`;
      }
      const pairs = updateCols.map((c) => `${quoteId(c)} = VALUES(${quoteId(c)})`).join(", ");
      return `INSERT INTO ${tableQuoted} (${colsQuoted}) VALUES ${allPlaceholders} ON DUPLICATE KEY UPDATE ${pairs};`;
    }

    if (mode === "ignore" || updateCols.length === 0) {
      return `INSERT INTO ${tableQuoted} (${colsQuoted}) VALUES ${allPlaceholders} ON CONFLICT DO NOTHING;`;
    }
    const pairs = updateCols.map((c) => `${quoteId(c)} = excluded.${quoteId(c)}`).join(", ");
    return `INSERT INTO ${tableQuoted} (${colsQuoted}) VALUES ${allPlaceholders} ON CONFLICT (${pkQuoted}) DO UPDATE SET ${pairs};`;
  }

  function insertIgnorePivotSql(tableQuoted, colAQuoted, colBQuoted) {
    const p1 = param(1);
    const p2 = param(2);
    if (normalized === "mysql") {
      return `INSERT IGNORE INTO ${tableQuoted} (${colAQuoted}, ${colBQuoted}) VALUES (${p1}, ${p2});`;
    }
    if (normalized === "postgres") {
      return `INSERT INTO ${tableQuoted} (${colAQuoted}, ${colBQuoted}) VALUES (${p1}, ${p2}) ON CONFLICT DO NOTHING;`;
    }
    return `INSERT OR IGNORE INTO ${tableQuoted} (${colAQuoted}, ${colBQuoted}) VALUES (${p1}, ${p2});`;
  }

  function forUpdateSql(isLocked) {
    if (!isLocked || normalized === "sqlite") return "";
    return " FOR UPDATE";
  }

  function beginTxSql() {
    return normalized === "sqlite" ? "BEGIN IMMEDIATE;" : "BEGIN;";
  }

  function explainSql(selectSql) {
    return normalized === "sqlite" ? `EXPLAIN QUERY PLAN ${selectSql}` : `EXPLAIN ${selectSql}`;
  }

  function inspectColumnsQuery(tableName) {
    if (normalized === "postgres") {
      return {
        sql: "SELECT column_name AS name, data_type AS type, is_nullable FROM information_schema.columns WHERE table_schema = 'public' AND table_name = $1 ORDER BY ordinal_position;",
        params: [tableName]
      };
    }
    if (normalized === "mysql") {
      return {
        sql: "SELECT COLUMN_NAME AS name, DATA_TYPE AS type, IS_NULLABLE AS is_nullable FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = ? ORDER BY ORDINAL_POSITION;",
        params: [tableName]
      };
    }
    return {
      sql: `PRAGMA table_info(${quoteId(tableName)});`,
      params: []
    };
  }

  function hasIndexQuery(tableName, indexName) {
    if (normalized === "mysql") {
      return {
        sql: "SELECT 1 FROM information_schema.statistics WHERE table_schema = DATABASE() AND table_name = ? AND index_name = ? LIMIT 1;",
        params: [tableName, indexName]
      };
    }
    return null;
  }

  function createIndexSql(tableQuoted, indexQuoted, colsQuoted) {
    if (normalized === "mysql") {
      return `CREATE INDEX ${indexQuoted} ON ${tableQuoted} (${colsQuoted});`;
    }
    return `CREATE INDEX IF NOT EXISTS ${indexQuoted} ON ${tableQuoted} (${colsQuoted});`;
  }

  function hasForeignKeyQuery(tableName, constraintName) {
    if (normalized === "mysql") {
      return {
        sql: "SELECT 1 FROM information_schema.table_constraints WHERE table_schema = DATABASE() AND table_name = ? AND constraint_name = ? AND constraint_type = 'FOREIGN KEY' LIMIT 1;",
        params: [tableName, constraintName]
      };
    }
    if (normalized === "postgres") {
      return {
        sql: "SELECT 1 FROM information_schema.table_constraints WHERE table_schema = 'public' AND table_name = $1 AND constraint_name = $2 AND constraint_type = 'FOREIGN KEY' LIMIT 1;",
        params: [tableName, constraintName]
      };
    }
    return null;
  }

  return {
    name: normalized,
    supportsDeferredFkInCreate: normalized === "sqlite",
    quoteId,
    param,
    serialize,
    escapeLiteral,
    mapColumnType,
    lengthFn,
    insertSql,
    upsertSql,
    insertIgnorePivotSql,
    forUpdateSql,
    beginTxSql,
    explainSql,
    inspectColumnsQuery,
    hasIndexQuery,
    createIndexSql,
    hasForeignKeyQuery
  };
}

export function normalizeDialectName(input = "sqlite") {
  const raw = String(input).toLowerCase();
  if (raw.startsWith("postgres")) return "postgres";
  if (raw.startsWith("mysql") || raw.startsWith("mariadb")) return "mysql";
  return "sqlite";
}